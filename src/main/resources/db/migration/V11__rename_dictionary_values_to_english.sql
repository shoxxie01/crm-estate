-- Nazwy stałych słownikowych z polskich na angielskie.
--
-- Etykiety w UI zostają polskie — zmieniają się wyłącznie identyfikatory, czyli
-- to, co Hibernate zapisuje w kolumnach słownikowych (`EnumType.STRING`).
-- Migracja przepisuje więc istniejące wiersze: `ddl-auto: validate` sprawdza
-- typ kolumny, ale nie jej zawartość, więc bez tego aplikacja wstałaby
-- normalnie, a wywróciłaby się dopiero przy odczycie starej oferty na
-- `No enum constant ...MIESZKANIE`.
--
-- Słowniki bez zmian: `Currency`, `EnergyClass`, `Portal` (nazwy własne
-- portali) oraz `Voivodeship` — nazwy województw też są nazwami własnymi,
-- a „LOWER_SILESIAN" byłoby mniej czytelne niż oryginał.
--
-- `V10` zostaje nietknięta, mimo że powstała na tej samej gałęzi: została już
-- zaaplikowana, a poprawianie zaaplikowanej migracji rozjeżdża sumę kontrolną
-- w `flyway_schema_history`. Stąd CHECK-i kalendarza przepisujemy tutaj.

-- CHECK-i trzeba zdjąć przed przepisaniem wartości — inaczej UPDATE odbije się
-- od starej listy dozwolonych nazw.
ALTER TABLE clients DROP CONSTRAINT ck_clients_status;
ALTER TABLE calendar_events DROP CONSTRAINT ck_calendar_events_status;
